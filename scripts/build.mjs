#!/usr/bin/env node
/**
 * scripts/build.mjs — zero-dependency client bundle builder.
 *
 * Concatenates the client sources listed in ORDER into the single CommonJS-style
 * bundle that DSH's client module loader consumes (`window.__ModuleLoader__.load`).
 * The bundle format is fixed by docs/protocol.md §2.
 *
 * Usage:
 *   node scripts/build.mjs           write client.js when it is stale
 *   node scripts/build.mjs --check   never write; exit 1 when client.js is stale/missing
 *
 * Output is deterministic: sources are read in ORDER, line endings are normalised
 * to LF, and a single trailing newline is enforced, so two consecutive runs write
 * byte-identical files.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/** Client modules, in dependency order (docs/protocol.md §2). `app` must be last. */
export const ORDER = ['util', 'i18n', 'state', 'rpc', 'open-in-app', 'diff', 'diff-view', 'styles', 'ui', 'components', 'app'];

/** DSH client bundle id; must match package.json name. */
export const BUNDLE_ID = 'dsh-code-review';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CLIENT_DIR = path.join(ROOT, 'src', 'client');
const OUT_FILE = path.join(ROOT, 'client.js');

/** Modules the client half may pull from the host-provided factory table. */
const ALLOWED_REQUIRES = new Set([...ORDER, 'react']);

/** Thrown for source files that cannot be bundled; the message is user-facing. */
export class BuildError extends Error {
  constructor(message) {
    super(message);
    this.name = 'BuildError';
  }
}

const HEADER = `/* Generated by scripts/build.mjs from src/client/*.js — do not edit by hand. */
window.__ModuleLoader__.load({
  id: '${BUNDLE_ID}',
  factory(require) {
    const React = require('react');
    const __mods = Object.create(null);
    function __def(name, fn) {
      __mods[name] = { fn: fn, exports: null };
    }
    function __req(name) {
      const mod = __mods[name];
      if (!mod) throw new Error('dsh-code-review client: unknown module ' + name);
      if (!mod.exports) {
        mod.exports = {};
        mod.fn(mod.exports, __req, React);
      }
      return mod.exports;
    }
`;

const FOOTER = `
    return __req('app');
  },
});
`;

/** Normalise line endings and guarantee exactly one trailing newline. */
function normalise(text) {
  return text.replace(/\r\n?/g, '\n').replace(/\n+$/, '') + '\n';
}

/**
 * Strip line and block comments while preserving string/template contents and
 * newlines. Used only for lint-style checks; never emitted into the bundle.
 */
export function stripComments(src) {
  let out = '';
  let i = 0;
  const n = src.length;
  while (i < n) {
    const c = src[i];
    const next = src[i + 1];
    if (c === '/' && next === '/') {
      while (i < n && src[i] !== '\n') i += 1;
      continue;
    }
    if (c === '/' && next === '*') {
      i += 2;
      while (i < n && !(src[i] === '*' && src[i + 1] === '/')) {
        if (src[i] === '\n') out += '\n';
        i += 1;
      }
      i += 2;
      continue;
    }
    if (c === "'" || c === '"' || c === '`') {
      const quote = c;
      out += c;
      i += 1;
      while (i < n && src[i] !== quote) {
        if (src[i] === '\\') {
          out += src[i] + (src[i + 1] ?? '');
          i += 2;
          continue;
        }
        out += src[i];
        i += 1;
      }
      if (i < n) {
        out += src[i];
        i += 1;
      }
      continue;
    }
    out += c;
    i += 1;
  }
  return out;
}

/** Return the offset of the first meaningful (non-whitespace, non-comment) byte. */
function firstCodeOffset(src) {
  let i = 0;
  const n = src.length;
  while (i < n) {
    const c = src[i];
    if (c === ' ' || c === '\t' || c === '\r' || c === '\n' || c === '\uFEFF') {
      i += 1;
      continue;
    }
    if (c === '/' && src[i + 1] === '/') {
      while (i < n && src[i] !== '\n') i += 1;
      continue;
    }
    if (c === '/' && src[i + 1] === '*') {
      i += 2;
      while (i < n && !(src[i] === '*' && src[i + 1] === '/')) i += 1;
      i += 2;
      continue;
    }
    return i;
  }
  return -1;
}

/** 1-based line number for an offset. */
function lineAt(src, offset) {
  let line = 1;
  for (let i = 0; i < offset && i < src.length; i += 1) {
    if (src[i] === '\n') line += 1;
  }
  return line;
}

/**
 * Lint one client source. Throws BuildError with a precise message on the first
 * problem so the release pipeline names exactly which file must change.
 */
export function checkSource(name, src) {
  const label = `src/client/${name}.js`;

  const code = firstCodeOffset(src);
  if (code === -1) throw new BuildError(`${label} is empty`);
  const head = src.slice(code, code + 128);
  const defRe = new RegExp(`^__def\\(\\s*(['"])${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\1\\s*,`);
  if (!defRe.test(head)) {
    throw new BuildError(
      `${label} must start with __def('${name}', ...) after leading whitespace/comments; found: ${JSON.stringify(head.slice(0, 40))}`,
    );
  }

  const codeOnly = stripComments(src);

  // No ESM syntax: modules are plain scripts concatenated into one factory.
  const esmRe = /(^|\n)[ \t]*(import|export)[ \t]/g;
  const esm = esmRe.exec(codeOnly);
  if (esm) {
    throw new BuildError(
      `${label}:${lineAt(codeOnly, esm.index + esm[0].indexOf(esm[2]))} contains ESM syntax ('${esm[2]}'); client sources must be plain scripts`,
    );
  }

  // Simple JSX heuristic: a capitalised tag name followed by attributes, '/>' or '>'.
  // Comparisons like `a < B` and `a<B && c` do not match.
  const jsxRe = /<[A-Z][A-Za-z0-9_]*(\s+[A-Za-z-]+\s*=|\s*\/?>)/;
  const jsx = jsxRe.exec(codeOnly);
  if (jsx) {
    throw new BuildError(
      `${label}:${lineAt(codeOnly, jsx.index)} looks like JSX (${JSON.stringify(jsx[0].slice(0, 24))}); use React.createElement instead`,
    );
  }

  // Every require('x') must name a module provided by the bundle factory.
  const requireRe = /require\(\s*(['"])([^'"]+)\1\s*\)/g;
  let m;
  while ((m = requireRe.exec(codeOnly)) !== null) {
    const required = m[2];
    if (!ALLOWED_REQUIRES.has(required)) {
      throw new BuildError(
        `${label}:${lineAt(codeOnly, m.index)} requires '${required}', which is not one of ${ORDER.join(', ')} (or 'react')`,
      );
    }
  }

  return { lineCount: src.split('\n').length };
}

/** Read and lint every source, then render the bundle string. */
export function renderBundle() {
  const sources = [];
  for (const name of ORDER) {
    const file = path.join(CLIENT_DIR, `${name}.js`);
    if (!existsSync(file)) {
      throw new BuildError(`missing client source: src/client/${name}.js`);
    }
    const raw = readFileSync(file, 'utf8');
    const body = normalise(raw);
    const stats = checkSource(name, body);
    sources.push({ name, file, body, bytes: Buffer.byteLength(body), lineCount: stats.lineCount });
  }

  let code = HEADER;
  for (const source of sources) {
    code += `// ===== src/client/${source.name}.js =====\n${source.body}`;
  }
  code += FOOTER;

  return {
    code,
    modules: sources.map((s) => s.name),
    moduleCount: sources.length,
    bytes: Buffer.byteLength(code),
  };
}

/** Compare two line arrays; returns a short, human-readable summary. */
function diffSummary(expected, actual) {
  const expectedLines = expected.split('\n');
  const actualLines = actual.split('\n');
  let first = 0;
  const max = Math.max(expectedLines.length, actualLines.length);
  while (first < max && expectedLines[first] === actualLines[first]) first += 1;
  const expectedBytes = Buffer.byteLength(expected);
  const actualBytes = Buffer.byteLength(actual);
  const where = first < max ? `first difference at line ${first + 1}` : 'trailing content differs';
  return `expected ${expectedLines.length} lines / ${expectedBytes} bytes, found ${actualLines.length} lines / ${actualBytes} bytes; ${where}`;
}

/**
 * Build (or freshness-check) the client bundle.
 * Never calls process.exit: the CLI entry point and validate.mjs share this function.
 */
export function buildClient({ check = false, root = ROOT } = {}) {
  const outFile = path.join(root, 'client.js');
  const { code, modules, moduleCount, bytes } = renderBundle();
  const exists = existsSync(outFile);
  const actual = exists ? readFileSync(outFile, 'utf8') : null;

  if (actual === code) {
    return { ok: true, stale: false, wrote: false, outFile, modules, moduleCount, bytes, reason: 'client.js is up to date' };
  }

  if (check) {
    const reason = exists
      ? `client.js is stale: ${diffSummary(code, actual)}`
      : `client.js is missing; run 'node scripts/build.mjs' (would generate ${moduleCount} modules / ${bytes} bytes)`;
    return { ok: false, stale: true, wrote: false, outFile, modules, moduleCount, bytes, reason };
  }

  writeFileSync(outFile, code, 'utf8');
  return {
    ok: true,
    stale: true,
    wrote: true,
    outFile,
    modules,
    moduleCount,
    bytes,
    reason: `client.js written from ${moduleCount} modules (${bytes} bytes)`,
  };
}

/** CLI entry point. */
function main(argv) {
  const check = argv.includes('--check');
  const unknown = argv.filter((a) => a !== '--check');
  if (unknown.length > 0) {
    console.error(`build: unknown argument(s): ${unknown.join(' ')}`);
    return 2;
  }

  let result;
  try {
    result = buildClient({ check });
  } catch (error) {
    if (error instanceof BuildError) {
      console.error(`build: ${error.message}`);
      return 1;
    }
    throw error;
  }

  if (check) {
    if (!result.ok) {
      console.error(`build --check: ${result.reason}`);
      return 1;
    }
    console.log(`client.js is fresh (${result.moduleCount} modules, ${result.bytes} bytes)`);
    return 0;
  }

  console.log(
    `client.js: ${result.moduleCount} modules, ${result.bytes} bytes (${result.wrote ? 'written' : 'up to date'})`,
  );
  return 0;
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : '';
if (invokedPath && invokedPath === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
