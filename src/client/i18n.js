  var HTTP_ERROR_PREFIX = 'transport/http-';

  /**
   * @param {object|null} error
   * @param {(key: string, vars?: object) => string} t
   * @returns {string} localized, safe description (never the host's raw message)
   */
  function describeError(error, t) {
    if (!error) return '';
    var translate = typeof t === 'function' ? t : function (key) { return String(key); };
    var code = error.code === undefined || error.code === null ? '' : String(error.code);
    if (code.indexOf(HTTP_ERROR_PREFIX) === 0) {
      return translate('error.transportHttp', { status: code.slice(HTTP_ERROR_PREFIX.length) });
    }
    var key = ERROR_KEYS[code];
    if (key) return translate(key);
    return translate('error.unknown');
  }

  function createI18n(initialLocale) {
    let locale = initialLocale === 'en' || initialLocale === 'zh' ? initialLocale : detectLocale();
    const listeners = new Set();
    function t(key, vars) {
      const dict = DICTIONARIES[locale] || DICTIONARIES.zh;
      const value = dict[key] !== undefined ? dict[key] : DICTIONARIES.zh[key] !== undefined ? DICTIONARIES.zh[key] : key;
      return interpolate(value, vars);
    }
    function getLocale() {
      return locale;
    }
    function setLocale(next) {
      if (next !== 'zh' && next !== 'en') return;
      if (next === locale) return;
      locale = next;
      for (const listener of Array.from(listeners)) {
        try {
          listener();
        } catch {
          /* a listener must not break the switch */
        }
      }
    }
    function subscribe(listener) {
      listeners.add(listener);
      return function () {
        listeners.delete(listener);
      };
    }
    return { t: t, getLocale: getLocale, setLocale: setLocale, subscribe: subscribe };
  }

